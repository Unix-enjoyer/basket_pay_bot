"""
Файл конфигурации бота.

Все настройки (токен, ID супер-админа, пути к файлам) хранятся в переменных
окружения — в файле .env, а не прямо в коде. Это нужно, чтобы случайно не
выложить токен бота в открытый доступ (например, если проект окажется в git).
"""

import os

from dotenv import load_dotenv

# Загружаем переменные из файла .env в окружение процесса.
# Если файла .env нет — просто ничего не произойдёт (и ниже сработают проверки).
load_dotenv()

# Токен бота, полученный от @BotFather в Telegram
BOT_TOKEN = os.getenv("BOT_TOKEN")

# Telegram user_id супер-админа. Его нельзя удалить командой /remove_admin.
# Узнать свой user_id можно, например, у бота @userinfobot
SUPER_ADMIN_ID = int(os.getenv("SUPER_ADMIN_ID", "0"))

# Путь к файлу базы данных SQLite (создастся автоматически при первом запуске)
DB_PATH = os.getenv("DB_PATH", "data/bot.db")

# Путь к папке с лог-файлами
LOG_DIR = os.getenv("LOG_DIR", "logs")

# Цена билета, которая используется только при самом первом запуске бота
# (когда в истории цен ещё нет ни одной записи). Дальше цена меняется
# командой /set_price и хранится в базе данных.
DEFAULT_PRICE = int(os.getenv("DEFAULT_PRICE", "1000"))

# Номер счёта получателя из чека Т-Банка (поле "Договор получателя").
# Если указан — бот будет проверять, что деньги пришли именно на этот счёт.
# Если оставить пустым в .env — проверка пропускается.
RECEIVER_CONTRACT = os.getenv("RECEIVER_CONTRACT", "")

# Ссылка/реквизиты для перевода, которые бот показывает пользователю при покупке билета
ACCOUNT_LINK = os.getenv("ACCOUNT_LINK", "(ссылка на счёт ещё не указана)")

# Дополнительные реквизиты для перевода (необязательно): номер карты, имя получателя и т.п.
# В .env это одна строка; если нужен перенос строки, пиши в ней \\n — бот заменит на настоящий.
PAYMENT_DETAILS = os.getenv("PAYMENT_DETAILS", "").replace("\\n", "\n").strip()

# Путь к картинке с QR-кодом для оплаты (необязательно), например assets/qr.jpg.
# Если файла нет — бот просто отправит текст без картинки.
PAYMENT_QR_PATH = os.getenv("PAYMENT_QR_PATH", "").strip()

# Организаторы, к которым отправляем людей при проблемах с оплатой.
# В .env через запятую, например: ORGANIZERS=@ivan, @olga
# Если оставить пустым — в репликах про организаторов список просто не показывается.
ORGANIZERS = os.getenv("ORGANIZERS", "").strip()

# ID группы в Telegram, участникам которой разрешено покупать билеты.
# Число вида -1001234567890 (у супергрупп всегда отрицательное).
# Как узнать: добавить в группу любого бота-помощника (например @RawDataBot) на минуту.
GROUP_CHAT_ID = int(os.getenv("GROUP_CHAT_ID", "0"))


# Проверяем на старте, что обязательные настройки заданы.
# Лучше упасть сразу с понятной ошибкой, чем потом гадать, почему бот не отвечает.
if not BOT_TOKEN:
    raise RuntimeError(
        "Не найден BOT_TOKEN. Проверь, что файл .env существует и в нём заполнена строка BOT_TOKEN."
    )

if SUPER_ADMIN_ID == 0:
    raise RuntimeError(
        "Не найден SUPER_ADMIN_ID. Проверь, что файл .env существует и в нём заполнена строка SUPER_ADMIN_ID."
    )

if GROUP_CHAT_ID == 0:
    raise RuntimeError(
        "Не найден GROUP_CHAT_ID. Проверь, что файл .env существует и в нём заполнена строка GROUP_CHAT_ID."
    )
