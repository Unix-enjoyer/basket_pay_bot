"""
Клавиатура (кнопки под полем ввода) и памятка команд для администраторов.

Кнопки в Telegram — это просто способ быстро отправить текстовое сообщение,
не печатая его руками. Сама логика команд всё равно вызывается только
настоящими командами (/set_price и т.д.), поэтому кнопки здесь — просто
подсказки и быстрый доступ к справке.
"""

from telegram import ReplyKeyboardMarkup

ADMIN_HELP_TEXT = (
    "Список команд администратора:\n\n"
    "/set_price <сумма> — изменить цену билета\n"
    "  пример: /set_price 1500\n\n"
    "/check_guest_list — посмотреть всех, кому выданы коды\n\n"
    "/add_admin — назначить админа. Нужно ОТВЕТИТЬ этой командой\n"
    "  на любое сообщение человека, которого хотите назначить\n\n"
    "/remove_admin — снять админа. Тоже ответом на его сообщение\n\n"
    "/add_guest <тег или телефон> — добавить гостя вручную (без чека)\n"
    "  пример: /add_guest @molodec\n\n"
    "/remove_guest <код> — удалить гостя по коду входа\n"
    "  пример: /remove_guest ABC123"
)

# Кнопки под полем ввода — показываются админу после /start.
# По нажатию на "Список команд" и "Список оплативших" бот сразу отвечает,
# остальные кнопки просто подсказывают, какую команду и с каким аргументом набрать
# (т.к. этим командам нужен параметр, который проще напечатать, чем выбрать кнопкой).
ADMIN_KEYBOARD = ReplyKeyboardMarkup(
    [
        ["📋 Список оплативших"],
        ["ℹ️ Список команд"],
    ],
    resize_keyboard=True,
)
